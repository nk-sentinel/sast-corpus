#!/usr/bin/env bash
# Parse every generated fixture in languages whose toolchain is present.
#
# A fixture that does not parse produces no findings from any tool, and in a
# scorecard that is indistinguishable from every tool missing it. Since the
# fixtures are generated from templates, one bad template silently poisons a
# whole language.
#
# Languages with no toolchain here are reported as skipped rather than passed.
# "We did not check" and "we checked and it was fine" must not look the same.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "${WORK}"' EXIT

FAILURES=0
declare -a SKIPPED=()

have() { command -v "$1" >/dev/null 2>&1; }

report() {
    local language="$1" checked="$2"
    if [ "${checked}" -eq 0 ]; then
        echo "  ${language}: no fixtures"
    else
        echo "  ${language}: ${checked} file(s) parsed"
    fi
}

check_language() {
    local language="$1" pattern="$2"
    shift 2
    local checked=0

    while IFS= read -r file; do
        checked=$((checked + 1))
        if ! "$@" "${file}" > "${WORK}/out" 2>&1; then
            echo "FAIL  ${file#"${ROOT}/"}" >&2
            sed 's/^/      /' "${WORK}/out" | head -8 >&2
            FAILURES=$((FAILURES + 1))
        fi
    done < <(find "${ROOT}/tier1/${language}" -name "${pattern}" -type f 2>/dev/null | sort)

    report "${language}" "${checked}"
}

echo "syntax checks:"

# PYTHONPYCACHEPREFIX keeps the generated bytecode out of the corpus tree; a
# scanner pointed at tier1/ would otherwise pick up __pycache__ as content.
if have python3; then
    export PYTHONPYCACHEPREFIX="${WORK}/pycache"
    check_language python "*.py" python3 -m py_compile
else
    SKIPPED+=("python")
fi

if have node; then
    check_language javascript "*.js" node --check
else
    SKIPPED+=("javascript")
fi

if have gofmt; then
    # gofmt parses without needing a module or resolvable imports.
    check_language go "*.go" gofmt -e -l
else
    SKIPPED+=("go")
fi

if have gcc; then
    check_language c "*.c" gcc -fsyntax-only -I"${ROOT}"
else
    SKIPPED+=("c")
fi

if have g++; then
    check_language cpp "*.cpp" g++ -fsyntax-only -std=c++17 -I"${ROOT}"
else
    SKIPPED+=("cpp")
fi

# rustc needs the crate root, not each file: main.rs pulls in its modules.
if have rustc; then
    checked=0
    while IFS= read -r crate; do
        checked=$((checked + 1))
        if ! rustc --edition 2021 --emit=metadata --crate-type bin \
                -o "${WORK}/meta" "${crate}" > "${WORK}/out" 2>&1; then
            echo "FAIL  ${crate#"${ROOT}/"}" >&2
            sed 's/^/      /' "${WORK}/out" | head -8 >&2
            FAILURES=$((FAILURES + 1))
        fi
    done < <(find "${ROOT}/tier1/rust" -name "main.rs" -type f 2>/dev/null | sort)
    report rust "${checked}"
else
    SKIPPED+=("rust")
fi

# Languages with no local toolchain but a small official image. Opt-in via
# SYNTAX_USE_DOCKER=1 so the default run stays offline and fast; CI sets it.
# Mounted read-only — a syntax check has no business writing to the corpus.
check_in_docker() {
    local language="$1" pattern="$2" image="$3" command="$4"
    local checked
    checked=$(find "${ROOT}/tier1/${language}" -name "${pattern}" -type f 2>/dev/null | wc -l)
    [ "${checked}" -eq 0 ] && { report "${language}" 0; return; }

    # The `while` runs in a subshell, so a variable set inside it cannot carry a
    # failure out. The FAIL lines on stdout are the only signal, and counting
    # them is also how many fixtures broke.
    if ! docker run --rm -v "${ROOT}:/w:ro" -w /w "${image}" sh -c "
            find tier1/${language} -name '${pattern}' -type f | sort | while IFS= read -r f; do
                ${command} \"\$f\" >/dev/null 2>&1 || echo \"FAIL  \$f\"
            done" > "${WORK}/out" 2>&1; then
        echo "FAIL  ${language}: ${image} did not run" >> "${WORK}/out"
    fi

    local broken
    broken=$(grep -c '^FAIL' "${WORK}/out")
    if [ "${broken}" -gt 0 ]; then
        grep '^FAIL' "${WORK}/out" >&2
        FAILURES=$((FAILURES + broken))
        echo "  ${language}: ${checked} file(s) checked, ${broken} did NOT parse"
        return
    fi
    report "${language}" "${checked}"
}

DOCKER_LANGUAGES=""
if [ "${SYNTAX_USE_DOCKER:-0}" = "1" ] && have docker; then
    check_in_docker php "*.php" php:8.3-cli "php -l"
    check_in_docker ruby "*.rb" ruby:3.3-slim "ruby -c"
    DOCKER_LANGUAGES="php ruby"
fi

for language in typescript csharp php ruby kotlin swift; do
    case " ${DOCKER_LANGUAGES} " in *" ${language} "*) continue ;; esac
    if [ -d "${ROOT}/tier1/${language}" ]; then
        SKIPPED+=("${language}")
    fi
done

if [ ${#SKIPPED[@]} -gt 0 ]; then
    echo
    echo "  not checked (no toolchain on this host): ${SKIPPED[*]}"
    echo "  fixtures in these languages are unverified, not verified-good."
fi

if [ "${FAILURES}" -gt 0 ]; then
    echo >&2
    echo "${FAILURES} fixture(s) do not parse; they would score as a miss for every tool." >&2
    exit 1
fi

echo
echo "all checked fixtures parse"
